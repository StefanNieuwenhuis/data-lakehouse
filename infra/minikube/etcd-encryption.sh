#!/usr/bin/env bash
# infra/minikube/etcd-encryption.sh - owner: platform-engineer (ADR-0006, #5).
#
# Manages the kube-apiserver EncryptionConfiguration for profile `dev`.
# The key is never printed: no `set -x`, and no command here echoes file
# contents.
#
#   ensure   create the source of truth if it is missing (secretbox first,
#            identity as read fallback, random 32-byte key, mode 0600). An
#            existing file is never changed or rotated; only its mode is fixed.
#   stage    copy it into minikube's file-sync tree, so `minikube start` puts
#            it on the node at NODE_PATH (a path the apiserver static pod
#            already mounts: kubeadm's certificatesDir /var/lib/minikube/certs).
#   unstage  remove the file-sync copy again (cluster-up runs it on exit), so
#            no copy lingers on the host and other profiles don't receive it.
#   node-path  print NODE_PATH (a path, not a secret).
#
# Host-side locations (listed for the Read deny rules, #15):
#   source : ~/.config/lakehouse/etcd/encryption-config.yaml
#   staged : ${MINIKUBE_HOME:-~}/.minikube/files/var/lib/minikube/certs/encryption-config.yaml
#            (only while `minikube start` runs)
set -euo pipefail

SRC_DIR="$HOME/.config/lakehouse/etcd"
SRC="$SRC_DIR/encryption-config.yaml"
NODE_PATH="/var/lib/minikube/certs/encryption-config.yaml"

minikube_home() {
  # Same resolution as minikube: MINIKUBE_HOME, with .minikube appended unless
  # it already ends in .minikube; default ~/.minikube.
  local h="${MINIKUBE_HOME:-}"
  if [ -z "$h" ]; then
    echo "$HOME/.minikube"
  elif [ "$(basename "$h")" = ".minikube" ]; then
    echo "$h"
  else
    echo "$h/.minikube"
  fi
}

STAGED="$(minikube_home)/files${NODE_PATH}"

file_mode() {
  if stat -f '%Lp' "$1" >/dev/null 2>&1; then
    stat -f '%Lp' "$1" # BSD/macOS
  else
    stat -c '%a' "$1" # GNU
  fi
}

ensure() {
  if [ -f "$SRC" ]; then
    if [ "$(file_mode "$SRC")" != "600" ]; then
      chmod 600 "$SRC"
      echo "etcd encryption config: existing file, mode reset to 0600"
    else
      echo "etcd encryption config: existing file kept (mode 0600, not rotated)"
    fi
    return 0
  fi
  umask 077
  mkdir -p "$SRC_DIR"
  chmod 700 "$SRC_DIR"
  local tmp key
  tmp="$(mktemp "$SRC_DIR/.encryption-config.XXXXXX")"
  trap 'rm -f "$tmp"' EXIT
  # 32 random bytes, base64-encoded (44 characters), as secretbox requires.
  key="$(head -c 32 /dev/urandom | base64 | tr -d '\n')"
  if [ "${#key}" -ne 44 ]; then
    echo "ERROR: generated etcd key has the wrong length" >&2
    exit 1
  fi
  cat >"$tmp" <<EOF
---
# Generated by make cluster-up (infra/minikube/etcd-encryption.sh). Never
# commit, copy or print this file. Losing it makes existing Secrets
# unreadable; recovery is a fresh cluster (ADR-0006).
apiVersion: apiserver.config.k8s.io/v1
kind: EncryptionConfiguration
resources:
  - resources:
      - secrets
    providers:
      - secretbox:
          keys:
            - name: key1
              secret: ${key}
      - identity: {}
EOF
  unset key
  chmod 600 "$tmp"
  mv "$tmp" "$SRC"
  trap - EXIT
  echo "etcd encryption config: generated (mode 0600, random 32-byte secretbox key)"
}

stage() {
  [ -f "$SRC" ] || {
    echo "ERROR: etcd encryption config missing; run '$0 ensure' first" >&2
    exit 1
  }
  umask 077
  mkdir -p "$(dirname "$STAGED")"
  cp "$SRC" "$STAGED"
  chmod 600 "$STAGED"
}

unstage() {
  rm -f "$STAGED"
}

case "${1:-}" in
  ensure) ensure ;;
  stage) stage ;;
  unstage) unstage ;;
  node-path) echo "$NODE_PATH" ;;
  *)
    echo "usage: $0 ensure|stage|unstage|node-path" >&2
    exit 2
    ;;
esac
